import { mkdir, readFile, writeFile } from 'node:fs/promises'
import { existsSync } from 'node:fs'
import { basename, join } from 'node:path'

const root = process.cwd()
const sourceFiles = ['src/data/aiTools.ts', 'src/data/aiCatalog.ts', 'src/data/websites.ts']
const outputDir = join(root, 'public', 'site-logos')
const force = process.argv.includes('--force')

await mkdir(outputDir, { recursive: true })

const hosts = new Set()
for (const file of sourceFiles) {
  const source = await readFile(join(root, file), 'utf8')
  for (const match of source.matchAll(/https?:\/\/[^'"\s]+/g)) {
    try { hosts.add(new URL(match[0]).hostname.replace(/^www\./, '').toLowerCase()) } catch { /* ignore malformed data URLs */ }
  }
}

const queue = [...hosts].sort()
let cursor = 0
let downloaded = 0
let skipped = 0
const failed = []

async function worker() {
  while (cursor < queue.length) {
    const host = queue[cursor++]
    const target = join(outputDir, `${host}.webp`)
    if (!force && existsSync(target)) {
      skipped++
      continue
    }

    try {
      const response = await fetch(`https://favicon.im/${host}?larger=true`, {
        signal: AbortSignal.timeout(15000),
        headers: { 'user-agent': 'EECO-Navigation-Logo-Cache/2.0' },
      })
      const contentType = response.headers.get('content-type') ?? ''
      if (!response.ok || !contentType.startsWith('image/')) throw new Error(`${response.status} ${contentType}`)
      const bytes = Buffer.from(await response.arrayBuffer())
      if (bytes.length < 100) throw new Error('image too small')
      await writeFile(target, bytes)
      downloaded++
      process.stdout.write(`✓ ${host}\n`)
    } catch (error) {
      failed.push(`${host}: ${error instanceof Error ? error.message : String(error)}`)
      process.stdout.write(`× ${host}\n`)
    }
  }
}

await Promise.all(Array.from({ length: Math.min(8, queue.length) }, () => worker()))
await writeFile(join(outputDir, 'README.txt'), `EECO website logo cache\nGenerated by scripts/${basename(import.meta.filename)}\nLogos are fetched from each site's favicon through favicon.im and used only for navigation identification.\n`, 'utf8')

console.log(`\nHosts: ${queue.length}; downloaded: ${downloaded}; cached: ${skipped}; failed: ${failed.length}`)
if (failed.length) console.log(failed.join('\n'))
